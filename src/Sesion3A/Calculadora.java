package Sesion3A;

public class Calculadora {
	public static Integer suma(int a, int b) {
		return a+b;
	}
	public static Integer resta(int a, int b) {
		return a-b;
	}
	public static Integer multiplicacion(int a, int b) {
		return a*b;
	}
	public static Integer division(int a, int b) {
		
			return a/b;
	}
}
